-- ---------------------------------------------------------------------------
-- Shared: transactional history (CE 3.0 qualifying elements live here)
-- ---------------------------------------------------------------------------
CREATE TABLE transactions (
  txn_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cardholder_id    text        NOT NULL,
  merchant_id      text        NOT NULL,
  amount           numeric(12,2) NOT NULL,
  currency         char(3)     NOT NULL DEFAULT 'USD',
  ts               timestamptz NOT NULL,
  descriptor       text        NOT NULL,
  settlement_batch text,                 -- ties disputes to recon (M4 tie-back)
  disputed         boolean     NOT NULL DEFAULT false,
  -- CE 3.0 qualifying data elements (≥2 must match across priors, ≥1 core):
  ip_addr          inet,                 -- core element
  device_id        text,                 -- core element
  shipping_addr    text,                 -- secondary
  email            text                  -- plays the account/login-ID role
);
CREATE INDEX ON transactions (cardholder_id, ts);
CREATE INDEX ON transactions (settlement_batch);

-- ---------------------------------------------------------------------------
-- Disputes track
-- ---------------------------------------------------------------------------
CREATE TABLE disputes (
  case_id        bigint PRIMARY KEY,     -- NOT identity: #4127 is authored
  txn_id         bigint      NOT NULL REFERENCES transactions,
  network        text        NOT NULL CHECK (network IN ('visa','mastercard')),
  reason_code    text        NOT NULL,
  amount         numeric(12,2) NOT NULL,
  complaint_text text        NOT NULL,
  status         text        NOT NULL DEFAULT 'OPEN'
                 CHECK (status IN ('OPEN','INVESTIGATING','DRAFTED','REVIEW',
                                   'FILED','ACCEPTED','DENIED','CLOSED')),
  evidence_score smallint    NOT NULL DEFAULT 0,   -- 0-3, feeds at_risk + confidence
  confidence     numeric(4,3),
  draft_text     text,
  trace_id       text,
  opened_at      timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON disputes (status);

-- The state machine as data: the M3 TODO-2 guard reads this table.
CREATE TABLE dispute_transitions (
  from_status text NOT NULL,
  to_status   text NOT NULL,
  PRIMARY KEY (from_status, to_status)
);
-- REVIEW is deliberately a dead end here: once a draft routes to a human,
-- NO agent-drivable edge leaves it — the review verdict path owns the case
-- from there. (No REVIEW→FILED / REVIEW→DENIED edges: with them, an agent
-- draining the queue can resolve a case out from under its review routing
-- via the equivalent-breaks path.)
INSERT INTO dispute_transitions VALUES
  ('OPEN','INVESTIGATING'), ('INVESTIGATING','DRAFTED'),
  ('DRAFTED','FILED'), ('DRAFTED','REVIEW'),
  ('FILED','ACCEPTED'), ('FILED','DENIED'),
  ('ACCEPTED','CLOSED'), ('DENIED','CLOSED');

-- Precedent corpus = {{ANALYST}}'s institutional memory.
-- analyst_id makes the 68/41 win-rate gap derivable (story acceptance check).
-- ⚠ NO B-tree on (reason_code, outcome) here — see header. Facilitator adds it in M2.
