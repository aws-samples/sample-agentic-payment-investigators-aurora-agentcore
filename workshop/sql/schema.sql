-- Copilot delegation: enqueue_task resolves the target queue
-- SERVER-SIDE from the referenced entity's type — the model never picks a specialist.
CREATE TABLE task_queue (
  task_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_agent text   NOT NULL CHECK (target_agent IN ('dispute','recon')),
  case_ref     bigint NOT NULL,
  instruction  text   NOT NULL,
  evidence_ref text,
  status       text   NOT NULL DEFAULT 'QUEUED'
               CHECK (status IN ('QUEUED','PICKED','DONE','REFUSED')),
  enqueued_by  text   NOT NULL,          -- copilot's actor_sub
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE FUNCTION enqueue_task(p_case_ref bigint, p_instruction text, p_evidence_ref text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_target text; v_id bigint;
BEGIN
  -- FK lookup, not a model choice (red-team pin):
  IF EXISTS (SELECT 1 FROM disputes WHERE case_id = p_case_ref) THEN
    v_target := 'dispute';
  ELSIF EXISTS (SELECT 1 FROM breaks WHERE break_id = p_case_ref) THEN
    v_target := 'recon';
  ELSE
    RAISE EXCEPTION 'enqueue_task: no dispute or break with id % — anchor tasks to an existing case', p_case_ref;
  END IF;
  INSERT INTO task_queue (target_agent, case_ref, instruction, evidence_ref, enqueued_by)
  VALUES (v_target, p_case_ref, p_instruction, p_evidence_ref, current_setting('app.analyst_id', true))
  RETURNING task_id INTO v_id;
  RETURN v_id;
END $$;

-- ---------------------------------------------------------------------------
-- Rubric views: cross-domain judgment lives HERE, not in the copilot's prompt
-- (red-team God-agent guard). Deterministic, explainable, seed-checked.
-- ---------------------------------------------------------------------------
CREATE VIEW at_risk AS
SELECT d.case_id,
       d.reason_code,
       d.amount,
       d.status,
       (20 - EXTRACT(day FROM now() - d.opened_at))::int          AS days_to_deadline,
       d.evidence_score,
       -- rubric: deadline proximity × amount band × missing evidence
       ( GREATEST(0, 10 - (20 - EXTRACT(day FROM now() - d.opened_at)))::numeric * 0.5
       + LEAST(d.amount / 1000.0, 3.0) * 0.25
       + (3 - d.evidence_score) * 0.75 )                          AS risk_score
FROM disputes d
WHERE d.status NOT IN ('ACCEPTED','DENIED','CLOSED');

