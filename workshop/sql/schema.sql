-- workshop_app deliberately has NO DELETE grant. The one
-- legitimate delete on the floor is the storm demo's own cleanup: retagging
-- (the old approach) left the demo vectors RESIDENT IN THE HNSW GRAPH —
-- 12k+ dead-weight neighbors that starve iterative scans at default limits
-- (observed symptom: hybrid top-k returned 1 of 5 post-storm).
-- SECURITY DEFINER scopes the delete to exactly the storm's own rows;
-- table-wide DELETE stays forbidden.
CREATE OR REPLACE FUNCTION purge_storm_rows() RETURNS bigint
LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  WITH gone AS (
    DELETE FROM precedent_cases
    WHERE tag IN ('storm', 'storm_done')
    RETURNING 1)
  SELECT count(*) FROM gone;
$$;
GRANT EXECUTE ON FUNCTION purge_storm_rows TO workshop_app;
