-- Network rulebook: deterministic join FIRST (rule_mappings), prose rank second (M2.4)
CREATE TABLE rule_clauses (
  clause_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  network          text NOT NULL,
  citation         text NOT NULL,        -- e.g. 'VCR 11.3.2 / CE3.0 element table'
  clause_text      text NOT NULL,
  clause_embedding vector(1024)
);
CREATE TABLE rule_mappings (
  network     text   NOT NULL,
  reason_code text   NOT NULL,
  clause_id   bigint NOT NULL REFERENCES rule_clauses,
  PRIMARY KEY (network, reason_code, clause_id)
);

